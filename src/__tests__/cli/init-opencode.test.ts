describe('filesystem integration (temporary directory)', () => {
  let tempDir: string;

  beforeEach(() => {
    tempDir = mkdtempSync(join(tmpdir(), 'opencode-init-test-'));
  });

  afterEach(() => {
    rmSync(tempDir, { recursive: true, force: true });
  });

  it('installOpenCodePlugin writes loader to target file', () => {
    const origCwd = process.cwd();
    process.chdir(tempDir);
    try {
      const written = installOpenCodePlugin('project', '/my/dist/opencode/index.js');
      expect(existsSync(written)).toBe(true);
      const content = readFileSync(written, 'utf-8');
      expect(content).toContain('import plugin from "/my/dist/opencode/index.js";');
      expect(content).toContain('export default plugin;');
    } finally {
      process.chdir(origCwd);
    }
  });

  it('registerOpenCodeMcp creates new config when absent', () => {
    const origCwd = process.cwd();
    process.chdir(tempDir);
    try {
      registerOpenCodeMcp('project', true, '/dist/index.js');
      const configPath = join(tempDir, 'opencode.jsonc');
      expect(existsSync(configPath)).toBe(true);
      const content = JSON.parse(readFileSync(configPath, 'utf-8'));
      expect(content.mcp.memory).toBeDefined();
      expect(content.mcp.memory.command).toEqual(['node', '/dist/index.js']);
    } finally {
      process.chdir(origCwd);
    }
  });

  it('registerOpenCodeMcp skips when disabled', () => {
    const origCwd = process.cwd();
    process.chdir(tempDir);
    try {
      registerOpenCodeMcp('project', false, '/dist/index.js');
      const configPath = join(tempDir, 'opencode.jsonc');
      expect(existsSync(configPath)).toBe(false);
    } finally {
      process.chdir(origCwd);
    }
  });
});
